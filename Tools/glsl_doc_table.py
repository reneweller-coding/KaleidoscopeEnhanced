# The coordinate transforms of the chains (tRot, tSpiral ...): the first parameter and the result
T_UV = "The coordinate."
T_RET = "The transformed coordinate."
CENTRE = "Centre of the transform."
# What the parameters of the chain transforms mean unless an entry says otherwise
T_DEFAULTS = {
    "uv": T_UV, "c": CENTRE,
    "t": "Phase (integrated time).", "steps": "Number of iterations.", "iters": "Number of iterations.",
    "travel": "Flow phase along the pattern.", "zoom": "Zoom phase (integrated time).",
    "a1": "Turn of the sphere about x (radians).", "a2": "Turn of the sphere about z (radians).",
    "K": "Scale ratio between two repeats.", "scale": "Scale of the coordinate.",
    "strength": "Strength of the displacement.", "turn": "Turn (radians).", "amp": "Amplitude.", "freq": "Frequency.",
}


def T( brief=None, **params ):
    """The entry of a chain transform: uv in, the transformed coordinate out (c, where given, is its centre)."""
    e = { "params": dict( T_DEFAULTS, **params ), "return": T_RET }
    if brief:
        e[ "brief" ] = brief
    return e


