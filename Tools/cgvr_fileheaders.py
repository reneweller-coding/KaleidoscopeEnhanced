# -*- coding: utf-8 -*-
r"""Gives every C++ file the file header of the CGVR templates (template.h, template.cpp).

    //---------------------------------------------------------------------------      (headers)
    //                              AudioAnalyzer
    //---------------------------------------------------------------------------
    //  Copyright (C): 2026 reneweller, MIT License (see LICENSE)
    //---------------------------------------------------------------------------

    /*****************************************************************************\    (sources)
     *                              AudioAnalyzer
    \*****************************************************************************/

followed by the Doxygen block of both templates:

    /*! @file
     *
     *  @brief
     *  One line.
     *
     *  The details ...
     *
     *  @author René Weller
     */

The text comes from the file's existing `@file` block.  Files written by others name their authors (ORIGINS); the
generated mainwindow.h is left alone.

Usage:
    python Tools/cgvr_fileheaders.py           # report what would change
    python Tools/cgvr_fileheaders.py --apply
"""
import argparse
import os
import re
import subprocess
import sys
import textwrap

sys.path.insert( 0, os.path.dirname( os.path.abspath( __file__ ) ) )
import cgvr_comments                                        # noqa: E402
import cgvr_format                                          # noqa: E402

ROOT = os.path.dirname( os.path.dirname( os.path.abspath( __file__ ) ) )
AUTHOR = "René Weller"
COPYRIGHT = "2026 reneweller, MIT License (see LICENSE)"
WIDTH = 116
SKIP = { "Source/mainwindow.h" }          # generated by uic from mainwindow.ui
KEEP_SECOND = { "Source/NowPlaying.cpp" }  # the comment after the @file block belongs to the #defines below it

# Files that began as someone else's code: author line and copyright line of the header
ORIGINS = {
    "stdinc.h":     ( "Frank Firsching (15.09.2001); adapted by " + AUTHOR, "2001 Frank Firsching; changes " + COPYRIGHT ),
    "Vector3D.h":   ( "Frank Firsching (17.03.2001); adapted by " + AUTHOR, "2001 Frank Firsching; changes " + COPYRIGHT ),
    "Vector3D.cpp": ( "Frank Firsching (17.03.2001); adapted by " + AUTHOR, None ),
    "Vector4D.h":   ( "Frank Firsching (17.03.2001); adapted by " + AUTHOR, "2001 Frank Firsching; changes " + COPYRIGHT ),
    "Uniform.h":    ( "Markus Kramer (Shader Maker, 2007-2008); trimmed down by " + AUTHOR,
                      "2007-2008 Markus Kramer (Shader Maker, see COPYING there); changes " + COPYRIGHT ),
    "Uniform.cpp":  ( "Markus Kramer (Shader Maker, 2007-2008); trimmed down by " + AUTHOR, None ),
    "textfile.h":   ( "www.lighthouse3d.com (\"You may use these functions freely\"); adapted by " + AUTHOR,
                      "www.lighthouse3d.com; changes " + COPYRIGHT ),
    "textfile.cpp": ( "www.lighthouse3d.com (\"You may use these functions freely\"); adapted by " + AUTHOR, None ),
    "mesh.h":       ( "Stephan Mock and Randolf Schärfig, modified by cg.in.tu-clausthal; adapted by " + AUTHOR,
                      "Stephan Mock, Randolf Schärfig, cg.in.tu-clausthal; changes 2026 reneweller (MIT, see LICENSE)" ),
    "mesh.cpp":     ( "Stephan Mock and Randolf Schärfig, modified by cg.in.tu-clausthal; adapted by " + AUTHOR, None ),
}

# Text of merged comments that was mangled (a lost umlaut) or German
FIXES = { "Sch�rfig": "Schärfig", "modifiziert von": "modified by" }


def banner( name, header, copyright_ ):
    if header:
        rule = "//" + "-" * 75
        return [ rule, "//" + " " * 30 + name, rule, "//  Copyright (C): " + copyright_, rule ]
    return [ "/" + "*" * 77 + "\\", " *" + " " * 30 + name, "\\" + "*" * 77 + "/" ]


def file_block( brief, details, author ):
    out = [ "/*! @file", " *", " *  @brief" ]
    out += [ " *  " + l for l in cgvr_comments.no_list_starts(
        textwrap.wrap( brief, WIDTH - 4, break_long_words=False, break_on_hyphens=False ) ) ]
    if details:
        out.append( " *" )
        out += [ ( " *  " + l ).rstrip() for l in details ]
    out += [ " *", " *  @author " + author, " */" ]
    return out


def leading_region( lines ):
    """(end, blocks): index of the first line after the comments at the top, and the comment blocks found there."""
    i, blocks = 0, []
    while i < len( lines ):
        s = lines[ i ].strip()
        if not s:
            i += 1
        elif s.startswith( "/*" ):
            j = i
            while "*/" not in lines[ j ][ ( lines[ j ].find( "/*" ) + 2 ) if j == i else 0: ]:
                j += 1
            blocks.append( ( i, j ) )
            i = j + 1
        elif s.startswith( "//" ):
            j = i
            while j + 1 < len( lines ) and lines[ j + 1 ].strip().startswith( "//" ):
                j += 1
            blocks.append( ( i, j ) )
            i = j + 1
        else:
            break
    return i, blocks


def split_file_text( text_lines ):
    """(brief, details) of a @file block's text, its @file line and @brief tag removed."""
    t = [ l for l in text_lines ]
    t = [ re.sub( r"^\s*[@\\]file\b[:\s]*\S*\s*", "", l, count=1 ) if re.match( r"^\s*[@\\]file\b", l ) else l for l in t ]
    while t and not t[ 0 ].strip():
        t.pop( 0 )
    if t and re.match( r"^\s*[@\\]brief\b", t[ 0 ] ):
        t[ 0 ] = re.sub( r"^\s*[@\\]brief\s*", "", t[ 0 ] )
    brief = []
    while t and t[ 0 ].strip() and not re.match( r"^\s*[@\\]\w+", t[ 0 ] ):
        brief.append( t.pop( 0 ).strip() )
    while t and not t[ 0 ].strip():
        t.pop( 0 )
    details = t
    while details and not details[ -1 ].strip():
        details.pop()
    # the text's own indentation, less the common part
    ind = min( ( len( l ) - len( l.lstrip() ) for l in details if l.strip() ), default=0 )
    return " ".join( brief ), [ l[ ind: ] for l in details ]


def line_comment_text( block, base ):
    """The text of a `//` comment block at the top of a file, without rules and without the repeated file name."""
    out = [ re.sub( r"^\s*//\s?", "", l ) for l in block ]
    out = [ l for l in out if not re.match( r"^\s*[-=/*]{10,}\s*$", l ) ]
    if out and re.match( r"^\s*(Source/)?" + re.escape( base ) + r"\s*$", out[ 0 ] ):
        out.pop( 0 )
    if out:
        # "X.cpp -- see X.h.  More" / "X.h -- what it is" start with the file's name
        m = re.match( r"^\s*" + re.escape( base ) + r"\s*(—|--|-|:)\s*(.*)$", out[ 0 ] )
        if m:
            rest = m.group( 2 )
            out[ 0 ] = rest[ :1 ].upper() + rest[ 1: ]
    while out and not out[ 0 ].strip():
        out.pop( 0 )
    while out and not out[ -1 ].strip():
        out.pop()
    return out


def class_name( lines, base, path ):
    """The class the file is named after (looked up in the header for a .cpp), else the file's base name."""
    sibling = os.path.splitext( path )[ 0 ] + ".h"
    if path.endswith( ".cpp" ) and os.path.exists( sibling ):
        lines = lines + cgvr_format.read( sibling ).replace( "\r\n", "\n" ).split( "\n" )
    for l in lines:
        m = re.match( r"^\s*(class|struct)\s+(\w+)\b(?!\s*;)", l )
        if m and m.group( 2 ).lower() == base.lower():
            return m.group( 2 )
    return base


def process( rel, apply ):
    path = os.path.join( ROOT, rel )
    raw = cgvr_format.read( path )
    nl = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.replace( "\r\n", "\n" ).split( "\n" )
    end, blocks = leading_region( lines )
    base = os.path.basename( rel )
    name = class_name( lines, os.path.splitext( base )[ 0 ], path )
    header = rel.endswith( ".h" )
    if any( lines[ b[ 0 ] ].startswith( "/*! @file" ) for b in blocks ):
        return "done"
    if rel in KEEP_SECOND:
        blocks = blocks[ :1 ]
    doc = [ b for b in blocks if re.search( r"[@\\]file\b", "\n".join( lines[ b[ 0 ]:b[ 1 ] + 1 ] ) ) ]
    if len( doc ) != 1:
        return "manual (%d comment blocks at the top, %d with @file)" % ( len( blocks ), len( doc ) )
    first, last = doc[ 0 ]
    brief, details = split_file_text( cgvr_comments.strip_markers( lines[ first:last + 1 ] ) )
    if not brief:
        return "manual (no brief)"
    # further comments at the top describe the file too: their text joins the details
    for b in blocks:
        if b == doc[ 0 ]:
            continue
        if not all( lines[ k ].lstrip().startswith( "//" ) for k in range( b[ 0 ], b[ 1 ] + 1 ) ):
            return "manual (a second block comment at the top)"
        extra = line_comment_text( lines[ b[ 0 ]:b[ 1 ] + 1 ], base )
        if extra:
            details += ( [ "" ] if details else [] ) + extra
    author, copyright_ = ORIGINS.get( base, ( AUTHOR, COPYRIGHT ) )
    for k, v in FIXES.items():
        details = [ l.replace( k, v ) for l in details ]
    new = banner( name, header, copyright_ ) + file_block( brief, details, author )
    top = min( b[ 0 ] for b in blocks )
    bottom = max( b[ 1 ] for b in blocks )
    lines[ top:bottom + 1 ] = new + ( [ "" ] if lines[ bottom + 1 ].strip() else [] )
    if apply:
        with open( path, "wb" ) as fh:
            fh.write( nl.join( lines ).encode( "utf-8" ) )
    return "rewritten"


def main():
    ap = argparse.ArgumentParser( description=__doc__.split( "\n" )[ 0 ] )
    ap.add_argument( "--apply", action="store_true" )
    a = ap.parse_args()
    files = subprocess.run( [ "git", "ls-files", "Source/*.h", "Source/*.cpp", "PresetEditor/*.h", "PresetEditor/*.cpp",
                              "SetupTool/*.h", "SetupTool/*.cpp", "ExportTool/*.h", "ExportTool/*.cpp" ], cwd=ROOT, capture_output=True, text=True ).stdout.split()
    counts = {}
    for rel in files:
        if rel in SKIP:
            continue
        r = process( rel, a.apply )
        counts[ r.split( " " )[ 0 ] ] = counts.get( r.split( " " )[ 0 ], 0 ) + 1
        if r != "rewritten":
            print( "%-40s %s" % ( rel, r ) )
    print( counts )
    return 0


if __name__ == "__main__":
    sys.exit( main() )
