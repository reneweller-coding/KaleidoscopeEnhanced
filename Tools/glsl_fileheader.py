# -*- coding: utf-8 -*-
"""The file header of a shader in the layout of the CGVR template (template.cpp): a banner with the file's name and
the /*! @file block (one-line brief, the description, the author) -- right after the #version line, which GLSL
requires to come first.

The text comes from the shader's own /** @file Name @brief ... */ block (wherever it stood) or, for the passes
Tools/scenegen/make_chainpass.py writes, from its "// GENERATED by ..." line.  The brief is that description's first
sentence, the rest stays as written.  A shader adapted from someone else's work names its original author.

Tools/doc_shaders.py runs convert() first, so the generators write the same header.  Idempotent.
"""
import os
import re
import sys
import textwrap

sys.path.insert( 0, os.path.dirname( os.path.abspath( __file__ ) ) )
import cgvr_comments as C                                   # noqa: E402
from cgvr_fileheaders import AUTHOR, WIDTH, file_block      # noqa: E402

KISHIMISU = "kishimisu (the original shader, CC BY-NC-SA 4.0), " + AUTHOR + " (adaptation)"
SHADERTOY = "an unknown Shadertoy author (the original shader), " + AUTHOR + " (adaptation)"
IQ = AUTHOR + "; contains code by Inigo Quilez (iq, 2013, CC BY-NC-SA 3.0)"
# shaders built on someone else's work (their headers or code comments name the original)
AUTHORS = {
    "ChromeDreams.frag": KISHIMISU, "DiscoGodrays.frag": KISHIMISU, "FlowingWires.frag": KISHIMISU,
    "InsideSystem.frag": KISHIMISU, "NeonTubes.frag": KISHIMISU, "PsychedelicPills.frag": KISHIMISU,
    "SphereGrid.frag": KISHIMISU, "TheCore.frag": KISHIMISU, "Vortex.frag": KISHIMISU, "Voyager.frag": KISHIMISU,
    "FractalBloom.frag": KISHIMISU + "; palette after Inigo Quilez",
    "BreathingFractal.frag": SHADERTOY, "BreathingFractalNoir.frag": SHADERTOY, "BreathingFractalZoom.frag": SHADERTOY,
    "HexKaleido.frag": SHADERTOY, "MobiusOrbs.frag": SHADERTOY,
    "NoiseSpiral.frag": AUTHOR + " (after an idea on Shadertoy)",
    "Bubble.frag": IQ, "FxDeformationFlow.frag": IQ, "FxPlaneFlight.frag": IQ, "FxSphere.frag": IQ, "FxWave.frag": IQ,
}


def banner( name ):
    """The template.cpp banner with the file's name."""
    return [ "/" + "*" * 77 + "\\", " *" + " " * 30 + name, "\\" + "*" * 77 + "/" ]


def describe( text_lines ):
    """(brief, details) of an old header's text (comment syntax removed)."""
    lines = [ l for l in text_lines if not re.match( r"^\s*@file\b", l ) ]
    author = None
    keep = []
    for l in lines:
        m = re.match( r"^\s*@author\s+(.*)$", l )
        if m:
            author = m.group( 1 ).strip()
        else:
            keep.append( l )
    while keep and not keep[ 0 ].strip():
        keep.pop( 0 )
    # the brief paragraph: from @brief (or the first line) to the first blank line
    first = 0
    while first < len( keep ) and not keep[ first ].strip():
        first += 1
    # it ends at a blank line, before a list or an indented line (kept as written), after a line that ends in a URL
    end = first
    indent = len( keep[ first ] ) - len( keep[ first ].lstrip() ) if first < len( keep ) else 0
    while end < len( keep ) and keep[ end ].strip():
        if end > first and ( len( keep[ end ] ) - len( keep[ end ].lstrip() ) > indent
                             or re.match( r"^\s*(\d+\)|[-*•]\s)", keep[ end ] ) ):
            break
        end += 1
        if re.search( r"https?://\S+$", keep[ end - 1 ].strip() ):
            break
    para = " ".join( re.sub( r"^\s*@brief\s*", "", l ).strip() for l in keep[ first:end ] )
    brief, rest = C.split_first_sentence( para )
    details = []
    if rest:
        details = C.no_list_starts( textwrap.wrap( rest, WIDTH - 4, break_long_words=False, break_on_hyphens=False ) ) + [ "" ]
    # the rest as written -- only a line too long for the block is wrapped (its indentation kept), so that a generator's
    # unwrapped source and an already laid-out file give the same header
    for l in keep[ end: ]:
        l = l.rstrip()
        if len( l ) <= WIDTH - 4:
            details.append( l )
            continue
        pad = l[ :len( l ) - len( l.lstrip() ) ]
        details += C.no_list_starts( textwrap.wrap( l.strip(), WIDTH - 4, initial_indent=pad, subsequent_indent=pad,
                                                   break_long_words=False, break_on_hyphens=False ) )
    while details and not details[ 0 ].strip():
        details.pop( 0 )
    while details and not details[ -1 ].strip():
        details.pop()
    # one blank line between paragraphs at most
    tidy = []
    for l in details:
        if l.strip() or ( tidy and tidy[ -1 ].strip() ):
            tidy.append( l )
    return brief, tidy, author


def convert( text, path ):
    """The shader's text with its header in the CGVR layout (unchanged if it has one)."""
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.replace( "\r\n", "\n" ).split( "\n" )
    name = os.path.basename( path ) if path else "shader"
    if any( l.startswith( "/*! @file" ) for l in lines[ :60 ] ):
        return text
    v = next( ( i for i, l in enumerate( lines[ :5 ] ) if l.startswith( "#version" ) ), -1 )
    found = None
    i = 0
    while i < min( len( lines ), 300 ):
        if lines[ i ].lstrip().startswith( "/*" ):
            j = i
            while j < len( lines ) and "*/" not in lines[ j ][ ( lines[ j ].find( "/*" ) + 2 ) if j == i else 0: ]:
                j += 1
            if any( "@file" in lines[ k ] for k in range( i, min( j + 1, len( lines ) ) ) ):
                found = ( i, j )
                break
            i = j + 1
        else:
            i += 1
    if found:
        i, j = found
        brief, details, author = describe( C.strip_markers( lines[ i:j + 1 ] ) )
        del lines[ i:j + 1 ]
        if 0 < i < len( lines ) and not lines[ i ].strip() and not lines[ i - 1 ].strip():
            del lines[ i ]
    else:
        # a generated chain pass: "// GENERATED by Tools/scenegen/make_chainpass.py from X -- what it is" (+ more //)
        k = v + 1
        if k >= len( lines ) or not lines[ k ].startswith( "// GENERATED by" ):
            return text
        e = k + 1
        # the comment goes on over the next // lines -- but never a run-time directive ("// @chain3d", read by the app)
        while e < len( lines ) and lines[ e ].startswith( "//" ) and not lines[ e ].startswith( "///" ) \
                and not re.match( r"^//\s*@\w", lines[ e ] ):
            e += 1
        said = " ".join( l[ 2: ].strip() for l in lines[ k:e ] )
        origin, _, what = said.partition( " -- " )
        what = what.strip() or "A generated shader."
        brief = what[ :1 ].upper() + what[ 1: ] + ( "" if what.endswith( "." ) else "." )
        details = [ origin.strip() + "." ]
        author = None
        del lines[ k:e ]
    head = banner( name ) + file_block( brief, details, author or AUTHORS.get( name, AUTHOR ) )
    lines[ v + 1:v + 1 ] = head
    return nl.join( lines )
