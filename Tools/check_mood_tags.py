#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Verify mood-tag coverage in the presets that are written by hand.

    python Tools/check_mood_tags.py

The mood tags live on every shader entry, and SceneScheduler::moodAccept reads them from whichever preset is
ACTIVE.  Since the genre presets are generated (Tools/make_genre_configs.py writes them from Komplett.xml, and
deliberately varies an entry's flags per preset -- a chain lab's "calm" variant in Ambient, an "aggressive" one in
Club), drift between presets is no longer a defect to repair: the generator is the one place the tags come from,
and editing a generated preset by hand is against the rules.  Until 16.10.2026 this script compared every preset
with the master and reported those variants as 294 "problems"; its --sync would have rewritten the generated files.

What is left to check is the source: every TextureShader / CombineShader / TransitionShader entry of a preset that
is NOT generated (Komplett.xml, the master; any other hand-made one) carries a mood attribute -- the neutral
defaults Crossfade and FxPlain excepted.  An entry without one would reach every genre preset untagged.

Exit code 1 on any finding, so this can gate a commit (release_check runs it in the step "rules").
"""
import glob
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = os.path.join(ROOT, "Presets")
GENERATED = "GENERATED by Tools/make_genre_configs.py"
ENTRY = re.compile(r"<(TextureShader|CombineShader|TransitionShader)\b[^>]*")
NEUTRAL = ("Crossfade.frag", "FxPlain.frag")


def main():
    problems, checked, entries = [], [], 0
    for path in sorted(glob.glob(os.path.join(CFG, "*.xml"))):
        s = io.open(path, encoding="utf-8", errors="replace").read()
        if GENERATED in s:
            continue
        name = os.path.basename(path)
        checked.append(name)
        for m in ENTRY.finditer(s):
            entries += 1
            f = re.search(r'file="([^"]+)"', m.group(0))
            base = re.split(r"[\\/]", f.group(1))[-1] if f else "?"
            if 'mood="' not in m.group(0) and base not in NEUTRAL:
                problems.append("%s: %s has no mood attribute" % (name, base))
    if problems:
        print("mood tags: %d problem(s)" % len(problems))
        for p in problems[:20]:
            print("  * %s" % p)
        if len(problems) > 20:
            print("  ... and %d more" % (len(problems) - 20))
        return 1
    print("mood tags OK: %d entries in %d hand-made preset(s) (%s), all tagged"
          % (entries, len(checked), ", ".join(checked)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
