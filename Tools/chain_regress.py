# -*- coding: utf-8 -*-
"""Regression test of the chain runner: every chain class, passes against the uber shader, pixel for pixel.

The app runs the chain labs as one small pass per transform (Engine/ChainPass,
generated by Tools/scenegen/make_chainpass.py); the editor and KALEIDO_NO_CHAINPASS
run the lab's own uber shader.  Both must give the same picture.  With
KALEIDO_FREEZE_TIME (the scene stands at one moment, silent audio),
KALEIDO_FIXED_PHOTO and KALEIDO_SEED two runs are pixel-identical, so any
difference is a bug in the generator or the runner.

Run i pins every stage to position i modulo its number of classes (the 2D lab's
positions, pickStage(knob, n) in the shader; the counts come from
Tools/scenegen/chain_classes.py -- 72, 33, 26 and 28 on 21.11.2026), so every
class of every stage is shown at least once in as many runs as stage A has
classes; the order, the time tilt and the look vary with i too.  Each run is a
full-resolution screenshot of the app (web remote /api/screenshot), once with
the runner and once without, on a private copy of the settings (KALEIDO_SETTINGS).
Until 21.11.2026 the counts were written in here (58, 23, 18, 20) and had fallen
behind the labs: run i showed another position than it printed, and 14 classes of
stage A were never shown.

  python Tools/chain_regress.py                 # all combinations (72, ~80 min)
  python Tools/chain_regress.py --every 6       # every 6th (12, ~14 min)
  python Tools/chain_regress.py --only 12 30    # these combinations
Exit code: the number of combinations whose mean difference exceeds --tol.
"""
import argparse, io, os, re, shutil, subprocess, sys, time, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REL = os.path.join(ROOT, "Release")
# KALEIDO_EXE: a copy of the app in Release/ (a long run goes on while the app is rebuilt)
EXE = os.environ.get("KALEIDO_EXE", "Kaleidoscope.exe")
sys.path.insert(0, os.path.join(ROOT, "Tools", "scenegen"))
import chain_classes as cc                                    # noqa: E402
from private_settings import PrivateSettings                  # noqa: E402
PS = None  # the private settings of this run (main())

# The number of classes of each stage, as the shaders pick them (pickStage(knob, n), position 0 = none).
N = {k: len(cc.CLASSES[k]) for k in ("chainAP", "chainBP", "chainCP", "chainDP")}
COMBOS = max(N.values())   # every class of every stage once


def preset(pins):
    src = io.open(os.path.join(ROOT, "Presets", "Komplett.xml"), encoding="utf-8").read()
    fx = re.search(r"[ \t]*<CombineShader\b[^>]*[\\/]FxPlain\.frag\"[^>]*>.*?</CombineShader>", src, re.S).group(0)
    blk = re.search(r"[ \t]*<TextureShader\b[^>]*[\\/]ChainLab2D\.frag\"[^>]*>.*?</TextureShader>", src, re.S).group(0)
    for k, v in pins.items():
        blk = re.sub(r'(<float name="%s") minValue="[^"]*" maxValue="[^"]*"' % k, r'\1 minValue="%s" maxValue="%s"' % (v, v), blk)
    head, rest = blk.split(">", 1)
    head = re.sub(r'\s(probability|minTimeSolo|maxTimeSolo)="[^"]*"', "", head)
    blk = head + ' probability="1.0" minTimeSolo="100" maxTimeSolo="120">' + rest
    return ('<?xml version="1.0" encoding="utf-8" ?>\n<configuration ImageDirectory="..' + "\\\\" + 'Images" '
            'ConfigurationName="_regress" hidden="true">\n' + blk + "\n" + fx + "\n</configuration>\n")


def shot(pins, out, runner, photo, wait):
    io.open(os.path.join(ROOT, "Presets", "_regress.xml"), "w", encoding="utf-8").write(preset(pins))
    env = PS.env(dict(os.environ, KALEIDO_MAX_RUNTIME_SECS=str(int(wait) + 10), KALEIDO_NO_ACTIVATE="1",
                      KALEIDO_FREEZE_TIME="30", KALEIDO_FIXED_PHOTO=photo, KALEIDO_SEED="7",
                      KALEIDO_CHAIN_SS="0"))   # supersampling changes the sparkling classes on purpose
    if not runner:
        env["KALEIDO_NO_CHAINPASS"] = "1"
    p = subprocess.Popen([os.path.join(REL, EXE), "-c", "_regress", "-l"], cwd=REL, env=env,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        for attempt in range(4):                              # the uber shader may still be compiling
            time.sleep(wait if attempt == 0 else 3)
            lg = io.open(os.path.join(REL, "kaleidoscope.log"), encoding="utf-8", errors="replace").read()
            m = re.search(r"WEB REMOTE: http://<this-pc>:(\d+)/", lg)
            try:
                urllib.request.urlopen(urllib.request.Request(
                    "http://127.0.0.1:%s/api/screenshot" % (m.group(1) if m else "8091"),
                    headers={"X-Kaleido": "1"}), timeout=5).read()   # an action: the remote wants the header
            except OSError:
                continue
            time.sleep(1.5)
            lg = io.open(os.path.join(REL, "kaleidoscope.log"), encoding="utf-8", errors="replace").read()
            saved = re.findall(r"Saved screenshot: (.*)", lg)
            if saved:
                f = saved[-1].strip()
                shutil.move(f if os.path.isabs(f) else os.path.join(REL, f), out)
                return True
        return False
    finally:
        p.wait(timeout=60)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--every", type=int, default=1, help="only every n-th combination")
    ap.add_argument("--only", type=int, nargs="*", help="these combinations (0..%d)" % (COMBOS - 1))
    ap.add_argument("--tol", type=float, default=0.5, help="mean absolute difference (0..255) that counts as a failure")
    ap.add_argument("--photo", default=None, help="the fixed photo (default: the first in Images/)")
    ap.add_argument("--wait", type=float, default=22.0,
                    help="seconds before the screenshot (the exposure settles on the frozen frame: ~20 s)")
    ap.add_argument("--pin", action="append", default=[], metavar="NAME=VALUE",
                    help="pin one more knob of the entry in every run, e.g. --pin depthLook=6")
    ap.add_argument("--keep", help="keep the screenshots in this folder")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    from PIL import Image
    import numpy as np
    photo = a.photo or sorted(os.listdir(os.path.join(ROOT, "Images")))[0]
    work = a.keep or os.path.join(os.environ.get("TEMP", "."), "chain_regress")
    os.makedirs(work, exist_ok=True)
    combos = a.only if a.only else list(range(0, COMBOS, a.every))
    global PS
    PS = PrivateSettings("regress")
    fails = 0
    try:
        for i in combos:
            pins = {k: "%.4f" % ((i % n + 0.5) / n) for k, n in N.items()}
            pins.update({"morphP": "0", "orderP": "%.4f" % ((i * 7 % 24 + 0.5) / 24), "tiltP": "%.2f" % (0.3 + 0.7 * (i % 3) / 2),
                         "styleP": "%.4f" % ((i % 5 + 0.5) / 5), "glowP": "0", "speedP": "0.5", "detailP": "0.6", "paletteP": "0.4"})
            pins.update(dict(x.split("=", 1) for x in a.pin))
            # the class the shader picks from the pinned knob: pickStage(x, n) = min(floor(x * n), n - 1)
            names = " | ".join(cc.CLASSES[k][min(int(float(pins[k]) * n), n - 1)] or "none" for k, n in N.items())
            ra, rb = os.path.join(work, "run_%02d.png" % i), os.path.join(work, "uber_%02d.png" % i)
            # A combination that fails is shown once more, with a longer wait.  After a change of the lab's text the
            # driver's shader cache is cold for every specialised copy it has not seen: the first start of a
            # combination then compiles past the wait and the screenshot shows the fallback or nothing (27.11.2026:
            # 9 of 12 "differed" in release_check after look 6's constants changed; each was identical at the second
            # start).  A real difference fails twice.
            d, got, again = 0.0, False, ""
            for attempt in (0, 1):
                w = a.wait + 18.0 * attempt
                got = shot(pins, ra, True, photo, w) and shot(pins, rb, False, photo, w + 2)
                if got:
                    x = np.asarray(Image.open(ra).convert("RGB")).astype(float)
                    y = np.asarray(Image.open(rb).convert("RGB")).astype(float)
                    d = abs(x - y).mean()
                if got and d <= a.tol:
                    break
                again = "  (second start; the first %s)" % ("differed by %.3f" % d if got else "gave no screenshot")
            if not got:
                print("%2d  NO SCREENSHOT  %s" % (i, names), flush=True)
                fails += 1
                continue
            bad = bool(d > a.tol)                       # a numpy bool would make fails a numpy int
            fails += bad
            print("%2d  %s  diff %.3f  %s%s" % (i, "FAIL" if bad else "ok  ", d, names, "" if bad else again),
                  flush=True)
    finally:
        PS.close()
        try:
            os.remove(os.path.join(ROOT, "Presets", "_regress.xml"))
        except OSError:
            pass
    print("%d of %d combinations differ" % (fails, len(combos)))
    sys.exit(min(int(fails), 255))              # sys.exit(numpy int) prints it and exits 1


if __name__ == "__main__":
    main()
